#!/usr/bin/env bash
# Release benchmark: luarc-compiled programs vs equivalent handwritten Rust.
#
#   bash bench/run.sh [runs]        (default: 5 runs per workload)
#
# Steps: (1) build everything in release mode and record compile times
# separately; (2) verify that each luarc program prints exactly what its Rust
# baseline prints; (3) time repeated runs (process start included) and report
# the median and min. Results are written to bench/RESULTS.md.
set -euo pipefail

RUNS="${1:-5}"
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
LUARC="$ROOT/target/release/luarc"
EXE=""
case "$(uname -s)" in MINGW* | MSYS* | CYGWIN*) EXE=".exe" ;; esac
OUT="$HERE/out"
mkdir -p "$OUT"

now_ms() { date +%s%N | awk '{ printf "%d", $1 / 1000000 }'; }

echo "building luarc (release)..." >&2
cargo build --release -p luarc --manifest-path "$ROOT/Cargo.toml" --quiet

WORKLOADS="numeric tables native"
declare -A COMPILE_MS
for w in $WORKLOADS; do
    t0=$(now_ms)
    (cd "$HERE" && "$LUARC" build "$w.luarc" --release -o "$OUT/luarc_$w$EXE")
    COMPILE_MS[$w]=$(( $(now_ms) - t0 ))
done
t0=$(now_ms)
cargo build --release --quiet --manifest-path "$HERE/rust_baseline/Cargo.toml" --target-dir "$OUT/rust_target"
RUST_COMPILE_MS=$(( $(now_ms) - t0 ))

median() { sort -n | awk '{ a[NR] = $1 } END { print a[int((NR + 1) / 2)] }'; }
minimum() { sort -n | head -1; }

time_runs() {
    local exe="$1"
    for _ in $(seq "$RUNS"); do
        local t0 t1
        t0=$(now_ms)
        "$exe" > /dev/null
        t1=$(now_ms)
        echo $(( t1 - t0 ))
    done
}

{
    echo "# Benchmark results"
    echo
    echo "Generated by \`bench/run.sh\` on $(date -u +%Y-%m-%d) — $(uname -s) $(uname -m), $(rustc --version)."
    echo "Each workload ran $RUNS times (wall clock, process start included). Release builds."
    echo
    echo "| workload | luarc median (ms) | luarc min | Rust median (ms) | Rust min | ratio (median) | output verified | luarc build (ms) |"
    echo "|---|---|---|---|---|---|---|---|"
} > "$HERE/RESULTS.md"

for w in $WORKLOADS; do
    L="$OUT/luarc_$w$EXE"
    R="$OUT/rust_target/release/$w$EXE"
    lo=$("$L")
    ro=$("$R")
    if [ "$lo" != "$ro" ]; then
        echo "output mismatch for $w:" >&2
        echo "  luarc: $lo" >&2
        echo "  rust:  $ro" >&2
        exit 1
    fi
    ltimes=$(time_runs "$L")
    rtimes=$(time_runs "$R")
    lmed=$(echo "$ltimes" | median); lmin=$(echo "$ltimes" | minimum)
    rmed=$(echo "$rtimes" | median); rmin=$(echo "$rtimes" | minimum)
    ratio=$(awk -v a="$lmed" -v b="$rmed" 'BEGIN { if (b == 0) b = 1; printf "%.2fx", a / b }')
    echo "| $w | $lmed | $lmin | $rmed | $rmin | $ratio | yes (\`$(echo "$lo" | tr '\t' ' ')\`) | ${COMPILE_MS[$w]} |" >> "$HERE/RESULTS.md"
    echo "$w: luarc ${lmed}ms vs rust ${rmed}ms ($ratio)" >&2
done

cat >> "$HERE/RESULTS.md" <<EOF

Handwritten Rust baselines (all three binaries) built in ${RUST_COMPILE_MS} ms.
luarc build times include type checking, Rust generation and the Cargo release
build of the generated package (incremental: the runtime and dependencies were
already compiled by the first build).

## What the numbers include

* **numeric** — f64 arithmetic in a numeric \`for\` loop. luarc lowers known-number
  locals to plain \`f64\` operations; \`%\` follows Luau's floor-modulo
  (\`a - floor(a/b)*b\`). The Rust baseline spells out the same formula, so the
  comparison measures code generation (Rust's \`%\` on f64 is a slower \`fmod\`).
* **tables** — array appends/iteration, a string-keyed map, and record allocation.
  luarc tables are shared \`Rc<RefCell<..>>\` handles: each access takes a runtime
  borrow, each record is a separate allocation, and string keys are hashed
  \`Rc<[u8]>\` byte strings built by concatenation. The baseline uses plain
  \`Vec\`/\`HashMap\`/structs without shared identity.
* **native** — calls into the fixture crate through generated wrappers:
  \`add(f64, f64)\` (no conversion cost beyond the \`Result\` channel),
  \`greet(&str) -> String\` (UTF-8 validation plus a copy into a source string), and
  \`largest(&[f64])\` with a 1000-element table (an \`O(n)\` snapshot of the table into a
  \`Vec\` for every call; this conversion cost is expected and documented).
EOF
echo "wrote $HERE/RESULTS.md" >&2
